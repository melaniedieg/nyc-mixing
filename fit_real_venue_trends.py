"""
fit_real_venue_trends.py

Real-data follow-up to validate_temporal_estimator.py's scenario E/F finding. That script showed
a SYNTHETIC per-venue random linear trend, with sigma_b=0.11 (in the same units as
improbable_copresence_cv), reproduces the real data's lag1..7 "excess" pattern almost exactly when
combined with a smaller genuine lag-1 correlation. This script checks whether the REAL balanced
T=8 panel actually shows trend heterogeneity of that magnitude, or whether that synthetic match
was a case of "a model COULD produce this shape" without being the right explanation.

Two checks:

1. PERMUTATION TEST on the per-venue fitted trend slope (valid, assumption-light): fit each
   venue's own closed-form OLS slope beta_v_hat = sum(c_m * r_vm) / sum(c_m^2) against centered
   month index c_m = m - 3.5 (sum(c_m^2) = 42 for T=8), then compare Var(beta_v_hat) across the
   real panel against its own null distribution -- generated by permuting each venue's OWN 8
   values across months (this destroys any genuine across-month structure, trend or otherwise,
   while exactly preserving that venue's own marginal 8 values, so no distributional assumptions
   are needed). This IS a valid test: under the null, beta_v_hat is just a fixed linear
   combination of that venue's own (possibly non-normal, heteroskedastic) noise, and permutation
   captures its true sampling distribution directly.
   RESULT: real Var(beta_v_hat) is ~26 permutation-null SDs above the null mean (Monte Carlo
   p<0.001) -- venues DO have more heterogeneous individual trajectories than pure within-venue
   noise would produce. But the implied sigma_b_hat (~0.0045, about 8% of one period's residual
   SD) is roughly 24x SMALLER than the sigma_b=0.11 the synthetic match needed. Real, but nowhere
   near large enough to be the (sole) explanation for the lag2..7 pattern.

2. A CAUTIONARY NEGATIVE RESULT, included deliberately rather than silently dropped: the natural
   next step -- remove each venue's OWN fitted trend (r_vm - rbar_v - beta_v_hat*c_m) and re-run
   the SAME lag-analysis on those "detrended" residuals, to see if the lag2..7 pattern collapses
   -- turns out to be INVALID. Run under a PURE NULL control (i.i.d. noise, zero true structure
   of any kind) through the identical detrend-then-lag-analyze procedure, it reproduces nearly
   the SAME large, dramatic lag1..7 shape as the real detrended data (see printed comparison).
   Fitting 2 parameters (intercept + slope) to only 8 points mechanically induces strong spurious
   correlation in the OLS residuals, concentrated at the endpoints (classic hat-matrix leverage
   effect for evenly-spaced x with so few points) -- it has nothing to do with real structure.
   This diagnostic doesn't work at this T, so its result is not usable evidence either way, and
   is reported here only so nobody re-tries it and gets fooled by the same artifact.

Net conclusion: the real per-venue trend heterogeneity is statistically real (permutation test)
but too small in magnitude to explain the lag2..7 "growing more negative" pattern on its own.
Pure AR(1) (checked separately, not shown here) doesn't match its shape either (bows in the
middle rather than decreasing monotonically). The lag2..7 pattern remains a genuine, unexplained
open question -- it does NOT, however, call into question the lag-1 finding itself, which
validate_temporal_estimator.py's scenarios A/B/C confirm independently and robustly.
"""
import os
import numpy as np
import pandas as pd

OUTPUT_DIR = os.environ.get("OUTPUT_DIR", "/home/claude/work/shared/output")
PERIODS = ("2025_12", "2026_01", "2026_02", "2026_03", "2026_04", "2026_05", "2026_06", "2026_07")
T = len(PERIODS)
rng = np.random.RandomState(31416)
N_PERM = 1000

frames = {}
for mm in PERIODS:
    d = pd.read_pickle(os.path.join(OUTPUT_DIR, f"results_mixing_{mm}.pkl"))
    rf = d["results_full"][["placekey", "improbable_copresence_cv"]].drop_duplicates(subset="placekey")
    frames[mm] = rf.set_index("placekey")
    print(f"{mm}: {len(rf)} eligible venues")

common = frames[PERIODS[0]].index
for mm in PERIODS[1:]:
    common = common.intersection(frames[mm].index)
print(f"\nbalanced T={T} panel: {len(common)} venues present in EVERY period")

R = np.column_stack([frames[mm].loc[common, "improbable_copresence_cv"].to_numpy() for mm in PERIODS])  # (N, T)
N = R.shape[0]
c = np.arange(T) - (T - 1) / 2.0
sum_c2 = np.sum(c ** 2)
print(f"sum(c_m^2) = {sum_c2}")

rbar = R.mean(axis=1)  # (N,)
beta_hat = (R - rbar[:, None]) @ c / sum_c2  # (N,) closed-form OLS slope per venue
fitted = rbar[:, None] + beta_hat[:, None] * c[None, :]
resid = R - fitted
sigma_eps2_hat = (resid ** 2).sum(axis=1) / (T - 2)  # per-venue noise variance, 6 df

var_beta_empirical = beta_hat.var(ddof=1)
noise_only_var = sigma_eps2_hat.mean() / sum_c2
tau_b2_hat = max(0.0, var_beta_empirical - noise_only_var)
r_period_sd = frames[PERIODS[-1]].loc[common, "improbable_copresence_cv"].std()
print(f"\nempirical Var(beta_v_hat) across {N} venues: {var_beta_empirical:.6f}")
print(f"expected sampling-noise-only variance (if sigma_b=0): {noise_only_var:.6f}")
print(f"method-of-moments tau_b_hat^2 = {tau_b2_hat:.6f}  ->  sigma_b_hat = {np.sqrt(tau_b2_hat):.4f} "
      f"({np.sqrt(tau_b2_hat) / r_period_sd * 100:.1f}% of one period's residual SD={r_period_sd:.4f})")
print("(compare to the synthetic scenario F's calibrated sigma_b=0.11 -- real is ~24x smaller)")

# ---- 1. permutation null on Var(beta_v_hat) -- VALID test ----
print(f"\n--- 1. permutation test on Var(beta_v_hat) ({N_PERM} within-venue permutations) ---")
perm_vars = np.empty(N_PERM)
for p in range(N_PERM):
    idx = np.argsort(rng.random((N, T)), axis=1)
    Rp = np.take_along_axis(R, idx, axis=1)
    rbar_p = Rp.mean(axis=1)
    beta_p = (Rp - rbar_p[:, None]) @ c / sum_c2
    perm_vars[p] = beta_p.var(ddof=1)

p_value = (perm_vars >= var_beta_empirical).mean()
print(f"null Var(beta_v_hat) under permutation: mean={perm_vars.mean():.6f} sd={perm_vars.std(ddof=1):.6f} "
      f"[2.5%ile={np.percentile(perm_vars, 2.5):.6f}, 97.5%ile={np.percentile(perm_vars, 97.5):.6f}]")
print(f"REAL (unpermuted) Var(beta_v_hat) = {var_beta_empirical:.6f}")
print(f"Monte Carlo p-value (real >= permutation null): {p_value:.4f}  "
      f"({'REJECTS no-trend null' if p_value < 0.01 else 'does not clearly reject null'})")
print(f"real value is {(var_beta_empirical - perm_vars.mean()) / perm_vars.std(ddof=1):.1f} "
      f"permutation-null SDs above the null mean")
print("-> statistically real trend heterogeneity, but ~24x too small to explain the lag2..7 "
      "pattern on its own (see validate_temporal_estimator.py scenario F's sigma_b=0.11).")


# ---- 2. the detrend-then-lag-analyze diagnostic: INVALID, shown via a null control ----
def lag_from_matrix(D):
    null_benchmark = -1.0 / (T - 1)
    out = []
    for lag in range(1, T):
        rs = []
        for i in range(T - lag):
            a, b = D[:, i], D[:, i + lag]
            mask = np.isfinite(a) & np.isfinite(b)
            rs.append(np.corrcoef(a[mask], b[mask])[0, 1])
        out.append(np.mean(rs) - null_benchmark)
    return np.array(out)


lag_plain_real = lag_from_matrix(R - rbar[:, None])
lag_detrended_real = lag_from_matrix(resid)

print(f"\n--- 2. detrend-then-lag-analyze: checking whether this diagnostic is even valid ---")
print("real data, plain demeaning (matches estimate_temporal_dependence.py):")
print("  lag1..7:", " ".join(f"{x:+.4f}" for x in lag_plain_real))
print("real data, TREND-REMOVED (r_vm - rbar_v - beta_v_hat*c_m):")
print("  lag1..7:", " ".join(f"{x:+.4f}" for x in lag_detrended_real))

print("\nnull control: pure i.i.d. noise (NO true trend, NO true serial correlation at all), "
      "run through the SAME detrend-then-lag-analyze procedure, 200 replicates:")
null_detrended = []
for _ in range(200):
    Rn = rng.normal(0, 1, (N, T))
    rbar_n = Rn.mean(axis=1)
    beta_n = (Rn - rbar_n[:, None]) @ c / sum_c2
    resid_n = Rn - (rbar_n[:, None] + beta_n[:, None] * c[None, :])
    null_detrended.append(lag_from_matrix(resid_n))
null_detrended_mean = np.array(null_detrended).mean(axis=0)
print("  lag1..7:", " ".join(f"{x:+.4f}" for x in null_detrended_mean))
print("\nThe pure-null control reproduces nearly the SAME large, dramatic shape as the real")
print("detrended data (both: moderate negative at lag1-2, crossing positive, blowing up to a")
print("large positive excess by lag7) with ZERO true structure of any kind. This diagnostic is")
print("a mechanical artifact of fitting 2 parameters to only T=8 points -- not usable evidence.")
print("CONCLUSION: the lag2..7 pattern in the plain-demeaned analysis remains unexplained by any")
print("mechanism tested so far (lag-1-only MA, full AR(1), or trend at its real estimated")
print("magnitude). It stays an open question; it does not affect the validated lag-1 finding.")
